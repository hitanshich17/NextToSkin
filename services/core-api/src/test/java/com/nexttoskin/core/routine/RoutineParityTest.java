/**
 * The recommender is moving from this Java engine to the FastAPI service. This test runs the Java rules on the real
 * catalog for many generated quiz profiles and stores inputs and results in testdata/routine-parity.json; the
 * Python port must reproduce every result (services/ai-service/tests/test_routine_parity.py).
 *
 * <p>Normally it checks that the file is current, so the two engines can't drift apart. After a deliberate rules
 * change, regenerate it: {@code ./mvnw test -Dtest=RoutineParityTest -Dparity.export=true}.
 */
@SpringBootTest
@Import(PostgresTestConfiguration.class)
@Testcontainers(disabledWithoutDocker = true)
class RoutineParityTest {

    // Covers the rules (RoutineRules) and the budget fit (RoutineSelector, MonthlyCost).
    static final Path GOLDEN = Path.of("../../testdata/routine-parity.json");
    static final int CASES = 500;

    @Autowired
    private CatalogImporter importer;

    @Autowired
    private RoutineCatalog routineCatalog;

    @Autowired
    private ProductSnapshots snapshots;

    @Autowired
    private JdbcTemplate jdbc;

    @Autowired
    private com.nexttoskin.core.feedback.FeedbackRepository feedbackRepository;

    @Autowired
    private com.nexttoskin.core.similarity.SimilarityRepository similarity;

    private final ObjectMapper json = new ObjectMapper().enable(SerializationFeature.INDENT_OUTPUT)
            .enable(SerializationFeature.ORDER_MAP_ENTRIES_BY_KEYS);

    static final Map<String, Climate> CLIMATES = Map.of(
            "phoenix", new Climate("Phoenix", "Arizona", 9.5, 14.5, 38.4, 10.4),
            "miami", new Climate("Miami", "Florida", 6.9, 23.6, 83.3, 6.2),
            "minneapolis", new Climate("Minneapolis", "Minnesota", 1.5, -14.4, 78.1, 7.0),
            "seattle", new Climate("Seattle", "Washington", 4.2, 10.3, 78.7, 5.0));

    @Test
    void goldenFileMatchesTheJavaEngine() throws Exception {
        jdbc.execute("TRUNCATE products CASCADE");
        importer.importDirectory(Path.of("../../catalog"));
        List<RoutineProduct> catalog = routineCatalog.load();
        String generated = json.writeValueAsString(golden(catalog));

        if (Boolean.getBoolean("parity.export")) {
            Files.writeString(GOLDEN, generated + "\n");
        }
        assertThat(Files.readString(GOLDEN).strip())
                .as("testdata/routine-parity.json is out of date: regenerate it with -Dparity.export=true")
                .isEqualTo(generated.strip());
    }

    private Map<String, Object> golden(List<RoutineProduct> catalog) {
        Map<String, Object> golden = new LinkedHashMap<>();
        golden.put("about", "Generated by RoutineParityTest from the Java rules engine; do not edit by hand.");
        golden.put("products", snapshots.all().stream().map(ProductSnapshots.Snapshot::product).toList());
        // The products as the Java engine sees them, to check the Python conversion from snapshots separately.
        golden.put("catalogView", catalog.stream().map(p -> {
            Map<String, Object> v = new LinkedHashMap<>();
            v.put("id", p.id());
            v.put("firstPositions", new TreeMap<>(p.firstPositions()));
            v.put("price", p.cheapestPriceCents());
            v.put("texture", p.texture().name());
            return v;
        }).toList());

        Random random = new Random(20261113);
        List<RoutineProduct> buyable = catalog.stream().filter(p -> p.offer() != null).toList();
        List<Map<String, Object>> cases = new ArrayList<>();
        for (int i = 0; i < CASES; i++) {
            QuizAnswers answers = randomAnswers(random);
            String climateName = pick(random, List.of("none", "none", "phoenix", "miami", "minneapolis", "seattle"));
            Climate climate = CLIMATES.get(climateName);
            Map<String, Object> triedJson = new LinkedHashMap<>();
            TriedProducts tried = randomTried(random, buyable, triedJson);

            RoutinePlan plan = RoutineRules.plan(answers, catalog, climate, tried);
            Map<String, Object> expected = new LinkedHashMap<>();
            Map<String, Object> candidates = new LinkedHashMap<>();
            Map<String, Object> reasons = new LinkedHashMap<>();
            for (Step step : Step.values()) {
                List<RoutineProduct> list = plan.candidates().get(step);
                candidates.put(step.name(), ids(list));
                if (!list.isEmpty()) {
                    reasons.put(step.name(), RoutineRules.reasons(answers, climate, tried, step, list.get(0)));
                }
            }
            expected.put("candidates", candidates);
            expected.put("reasons", reasons);
            expected.put("treatmentActive", plan.treatmentActive() == null ? null : plan.treatmentActive().name());
            expected.put("notes", plan.notes().stream().map(Enum::name).toList());
            Map<String, Object> fallbacks = new LinkedHashMap<>();
            plan.budgetFallbacks().forEach((active, list) -> fallbacks.put(active.name(), ids(list)));
            expected.put("budgetFallbacks", fallbacks);
            expected.put("budgetFallbackOrder", plan.budgetFallbacks().keySet().stream().map(Enum::name).toList());
            expected.put("owned", plan.owned().stream().map(RoutineProduct::id).sorted().toList());
            expected.put("avoided", plan.avoided());
            // Budget fit on the same plan: no limit, and a budget drawn from the slider's range.
            Integer budget = pick(random, List.of(3000, 4000, 5000, 6000, 8000, 12000));
            List<Map<String, Object>> routines = new ArrayList<>();
            for (Integer b : java.util.Arrays.asList(null, budget)) {
                routines.add(routineJson(RoutineSelector.select(plan, b)));
            }
            expected.put("routines", routines);

            Map<String, Object> c = new LinkedHashMap<>();
            c.put("answers", answersJson(answers));
            c.put("climate", climateName);
            c.put("tried", triedJson);
            c.put("expected", expected);
            cases.add(c);
        }
        golden.put("climates", CLIMATES);
        golden.put("cases", cases);
        golden.put("similarityCases", similarityCases(random, buyable));
        return golden;
    }

    private static QuizAnswers randomAnswers(Random random) {
        List<Concern> concerns = new ArrayList<>(List.of(Concern.values()));
        java.util.Collections.shuffle(concerns, random);
        int count = random.nextInt(3) == 0 ? 1 : 2;
        Set<Avoid> avoid = EnumSet.noneOf(Avoid.class);
        for (Avoid a : Avoid.values()) {
            if (random.nextInt(5) == 0) {
                avoid.add(a);
            }
        }
        return new QuizAnswers(pick(random, List.of(SkinType.values())), concerns.subList(0, count),
                pick(random, List.of(Reactivity.values())), avoid, pick(random, List.of(ActivesExperience.values())),
                pick(random, List.of(Pregnancy.values())), null, null,
                random.nextInt(3) == 0 ? null : 1 + random.nextInt(6));
    }

    private static TriedProducts randomTried(Random random, List<RoutineProduct> buyable, Map<String, Object> out) {
        List<Feedback> feedback = new ArrayList<>();
        Map<String, Double> similarity = new TreeMap<>();
        if (random.nextInt(2) == 0) {
            int n = 1 + random.nextInt(4);
            for (int i = 0; i < n; i++) {
                String id = buyable.get(random.nextInt(buyable.size())).id();
                if (feedback.stream().anyMatch(f -> f.productId().equals(id))) {
                    continue;
                }
                if (random.nextInt(3) == 0) {
                    feedback.add(new Feedback(id, Feedback.Verdict.LIKED, null));
                } else {
                    List<Feedback.Reason> reasons = new ArrayList<>(List.of(Feedback.Reason.values()));
                    reasons.add(null); // no reason given
                    feedback.add(new Feedback(id, Feedback.Verdict.DISLIKED, pick(random, reasons)));
                }
            }
            for (int i = 0; i < 6; i++) {
                similarity.put(buyable.get(random.nextInt(buyable.size())).id(),
                        Math.round((random.nextDouble() * 2 - 1) * 100) / 100.0);
            }
        }
        out.put("feedback", feedback.stream().map(f -> {
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("productId", f.productId());
            m.put("verdict", f.verdict().name());
            m.put("reason", f.reason() == null ? null : f.reason().name());
            return m;
        }).toList());
        out.put("similarity", similarity);
        return TriedProducts.from(feedback, similarity);
    }

    /** pgvector similarity scores for random likes and dislikes, from the vectors built at import. */
    private List<Map<String, Object>> similarityCases(Random random, List<RoutineProduct> buyable) {
        List<Map<String, Object>> cases = new ArrayList<>();
        for (int i = 0; i < 25; i++) {
            java.util.UUID client = new java.util.UUID(20261113L, i);
            List<Map<String, Object>> feedback = new ArrayList<>();
            int n = 1 + random.nextInt(4);
            for (int j = 0; j < n; j++) {
                String id = buyable.get(random.nextInt(buyable.size())).id();
                Feedback.Verdict verdict = random.nextBoolean() ? Feedback.Verdict.LIKED : Feedback.Verdict.DISLIKED;
                feedbackRepository.save(client, new Feedback(id, verdict, null), null);
                feedback.removeIf(f -> f.get("productId").equals(id)); // a new verdict replaces the old one
                feedback.add(Map.of("productId", id, "verdict", verdict.name()));
            }
            Map<String, Double> scores = new TreeMap<>();
            similarity.scores(client).forEach((id, score) -> scores.put(id, Math.round(score * 1e6) / 1e6));
            Map<String, Object> c = new LinkedHashMap<>();
            c.put("feedback", feedback);
            c.put("scores", scores);
            cases.add(c);
        }
        return cases;
    }

    private static Map<String, Object> routineJson(Routine r) {
        Map<String, Object> m = new LinkedHashMap<>();
        Map<String, Object> picks = new LinkedHashMap<>();
        r.picks().entrySet().stream().sorted(Map.Entry.comparingByKey()).forEach(e -> {
            Map<String, Object> pick = new LinkedHashMap<>();
            pick.put("product", e.getValue().product().id());
            pick.put("cheaper", ids(e.getValue().cheaperAlternatives()));
            pick.put("owned", e.getValue().owned());
            pick.put("cheaperForBudget", e.getValue().cheaperForBudget());
            picks.put(e.getKey().name(), pick);
        });
        m.put("budgetCents", r.budgetCents());
        m.put("picks", picks);
        m.put("treatmentActive", r.treatmentActive() == null ? null : r.treatmentActive().name());
        m.put("totalCents", r.totalCents());
        m.put("monthlyCents", r.monthlyCents());
        m.put("withinBudget", r.withinBudget());
        m.put("notes", r.notes().stream().map(Enum::name).toList());
        m.put("avoided", r.avoided());
        return m;
    }

    private static Map<String, Object> answersJson(QuizAnswers a) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("skinType", a.skinType().name());
        m.put("concerns", a.concerns().stream().map(Enum::name).toList());
        m.put("reactivity", a.reactivity().name());
        m.put("avoid", a.avoid().stream().map(Enum::name).sorted().toList());
        m.put("activesExperience", a.activesExperience().name());
        m.put("pregnancy", a.pregnancy().name());
        m.put("skinTone", a.skinTone());
        return m;
    }

    private static List<String> ids(List<RoutineProduct> products) {
        return products.stream().map(RoutineProduct::id).toList();
    }

    private static <T> T pick(Random random, List<T> values) {
        return values.get(random.nextInt(values.size()));
    }
}
